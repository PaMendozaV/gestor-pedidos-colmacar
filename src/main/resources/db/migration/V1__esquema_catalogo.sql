CREATE TABLE tmstatus (
    pkcodstatus integer PRIMARY KEY,
    dstatus     varchar(15) NOT NULL
);
CREATE TABLE tmusuario (
    pkcodusuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_usuario  varchar(15)  NOT NULL,
    con_usuario  varchar(260) NOT NULL,
    fkcods       integer      NOT NULL CONSTRAINT fk_cods REFERENCES tmstatus (pkcodstatus)
);
CREATE TABLE tmcategorias (
    pkcodcategoria   serial PRIMARY KEY,
    dcategoria       varchar(40) NOT NULL,
    imagen_categoria varchar(150)
);
CREATE TABLE tmproductos (
    pkcodproducto  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_p       varchar(100)  NOT NULL,
    precio         numeric(10,2) NOT NULL,
    fkcods         integer       NOT NULL CONSTRAINT fk_cods REFERENCES tmstatus (pkcodstatus),
    imagen_produ   varchar(100),
    precio_mayor   numeric(10,2),
    fkcodcategoria integer CONSTRAINT tmproductos_fkcodcategoria_fkey REFERENCES tmcategorias (pkcodcategoria)
);

