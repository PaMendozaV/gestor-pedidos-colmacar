-- V2: integra el catalogo con el gestor de pedidos AFD. Moneda unica: USD.

-- 1. Usuarios unificados (login Spring Security con BCrypt)
ALTER TABLE tmusuario ALTER COLUMN nom_usuario TYPE varchar(50);
ALTER TABLE tmusuario
    ADD COLUMN email    varchar(120),
    ADD COLUMN nombre   varchar(100),
    ADD COLUMN telefono varchar(20),
    ADD COLUMN rol      varchar(20) NOT NULL DEFAULT 'CLIENTE'
        CONSTRAINT ck_tmusuario_rol CHECK (rol IN ('ADMIN', 'CLIENTE', 'REPARTIDOR'));
UPDATE tmusuario SET rol = 'ADMIN' WHERE nom_usuario = 'admin';
-- Hashes scrypt heredados de Flask no sirven con BCrypt: el usuario queda inactivo hasta reasignar clave.
UPDATE tmusuario SET fkcods = 0 WHERE con_usuario NOT LIKE '$2%';
CREATE UNIQUE INDEX ux_tmusuario_nom   ON tmusuario (lower(nom_usuario));
CREATE UNIQUE INDEX ux_tmusuario_email ON tmusuario (lower(email)) WHERE email IS NOT NULL;

-- 2. Productos
ALTER TABLE tmproductos ALTER COLUMN imagen_produ TYPE varchar(255);

-- 3. Pedido (estados del AFD)
CREATE TABLE ttpedido (
    pkcodpedido    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         varchar(20) UNIQUE,
    fkcodusuario   integer       NOT NULL REFERENCES tmusuario (pkcodusuario),
    estado         varchar(30)   NOT NULL DEFAULT 'CARRITO'
        CHECK (estado IN ('CARRITO', 'PAGO_PENDIENTE', 'PAGO_RECHAZADO',
                          'PREPARANDO_INVENTARIO', 'EN_TRANSITO', 'ENTREGADO')),
    codigo_entrega varchar(4)    NOT NULL CHECK (codigo_entrega ~ '^[0-9]{4}$'),
    moneda         varchar(3)    NOT NULL DEFAULT 'USD' CHECK (moneda = 'USD'),
    subtotal       numeric(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    total          numeric(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    url_pago       varchar(600),
    congelado_en   timestamp,           -- se fija al aceptar CONFIRMAR_PEDIDO
    creado_en      timestamp     NOT NULL DEFAULT now(),
    actualizado_en timestamp     NOT NULL DEFAULT now(),
    version        bigint        NOT NULL DEFAULT 0
);
-- Un solo carrito abierto por cliente
CREATE UNIQUE INDEX ux_ttpedido_carrito ON ttpedido (fkcodusuario) WHERE estado = 'CARRITO';
CREATE INDEX ix_ttpedido_estado ON ttpedido (estado);

-- 4. Lineas del pedido (precio recalculado en backend; mayorista desde 50 unidades)
CREATE TABLE ttpedidodetalle (
    pkcoddetalle    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fkcodpedido     bigint        NOT NULL REFERENCES ttpedido (pkcodpedido) ON DELETE CASCADE,
    fkcodproducto   integer       NOT NULL REFERENCES tmproductos (pkcodproducto),
    nombre_p        varchar(100)  NOT NULL,   -- copia congelada
    cantidad        integer       NOT NULL CHECK (cantidad BETWEEN 1 AND 10000),
    precio_unitario numeric(10,2) NOT NULL CHECK (precio_unitario >= 0),
    es_mayorista    boolean       NOT NULL DEFAULT false,
    subtotal        numeric(12,2) NOT NULL CHECK (subtotal >= 0),
    CONSTRAINT ux_detalle_producto UNIQUE (fkcodpedido, fkcodproducto)
);

-- 5. Pagos (un pedido puede tener varios intentos)
CREATE TABLE ttpago (
    pkcodpago          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fkcodpedido        bigint        NOT NULL REFERENCES ttpedido (pkcodpedido),
    proveedor          varchar(20)   NOT NULL DEFAULT 'SANDBOX',
    referencia_externa varchar(255),
    estado             varchar(20)   NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
    monto              numeric(12,2) NOT NULL CHECK (monto >= 0),
    moneda             varchar(3)    NOT NULL DEFAULT 'USD' CHECK (moneda = 'USD'),
    creado_en          timestamp     NOT NULL DEFAULT now(),
    actualizado_en     timestamp     NOT NULL DEFAULT now()
);
CREATE INDEX ix_ttpago_pedido ON ttpago (fkcodpedido);

-- 6. Tablas del gestor que antes creaba Hibernate (auditoria e idempotencia del webhook)
CREATE TABLE registro_transicion (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_pedido  varchar(20)  NOT NULL,
    estado_origen  varchar(30)  NOT NULL,
    evento         varchar(30)  NOT NULL,
    fuente         varchar(30)  NOT NULL,
    estado_destino varchar(30)  NOT NULL,
    rol            varchar(20)  NOT NULL,
    aceptado       boolean      NOT NULL,
    detalle        varchar(200),
    fecha          timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX ix_registro_pedido ON registro_transicion (codigo_pedido);

CREATE TABLE evento_webhook (
    id            varchar(255) PRIMARY KEY,
    tipo          varchar(80)  NOT NULL,
    codigo_pedido varchar(20),
    recibido_en   timestamp    NOT NULL DEFAULT now()
);
